package com.gtnh.reforged.legacy.power.bridge.neoforge;

import com.gtnh.reforged.legacy.power.LegacyPowerDirection;
import com.gtnh.reforged.legacy.power.LegacyPowerNeighborCache;
import com.gtnh.reforged.legacy.power.LegacyPowerNeighborLookup;

import java.util.Objects;

import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.chunk.LevelChunk;

/**
 * Narrow Minecraft 26.3 world adapter for the legacy six-direction
 * adjacent-block-entity lookup and its per-cable neighbor cache.
 *
 * <p>Queries use {@link ServerLevel#getChunkSource()} and
 * {@link net.minecraft.server.level.ServerChunkCache#getChunkNow(int, int)}
 * rather than {@link ServerLevel#getBlockEntity(BlockPos)}. A missing loaded
 * chunk is reported as UNLOADED and is never synchronously requested or
 * generated by this adapter.</p>
 *
 * <p>Call this adapter on the logical server thread. The owning cable block
 * entity is responsible for invoking {@link #clearEmptyMarkers()} on legacy
 * null-marker lifecycle events and {@link #clearAll()} when its position
 * changes.</p>
 */
public final class NeoForgeLegacyPowerNeighborAccess {

    private final ServerLevel level;
    private final BlockPos origin;
    private final LegacyPowerNeighborCache cache;

    public NeoForgeLegacyPowerNeighborAccess(
        ServerLevel level,
        BlockPos origin,
        LegacyPowerNeighborCache cache) {
        this.level = Objects.requireNonNull(level, "level");
        this.origin = Objects.requireNonNull(origin, "origin").immutable();
        this.cache = Objects.requireNonNull(cache, "cache");
    }

    /**
     * Resolves the adjacent block entity, consulting the legacy cache first.
     * Loaded-empty and unloaded positions remain distinct in the returned
     * lookup result.
     */
    public LegacyPowerNeighborLookup getNeighbor(LegacyPowerDirection side) {
        Direction direction = toMinecraftDirection(side);
        BlockPos target = origin.relative(direction);
        boolean crossesChunkBorder = (origin.getX() >> 4) != (target.getX() >> 4)
            || (origin.getZ() >> 4) != (target.getZ() >> 4);

        LegacyPowerNeighborCache.CacheResult cached = cache.cachedResult(
            side,
            crossesChunkBorder,
            value -> value instanceof BlockEntity blockEntity && blockEntity.isRemoved(),
            value -> value instanceof BlockEntity blockEntity
                && blockEntity.getBlockPos().equals(target));

        switch (cached.status()) {
            case EMPTY:
            case MISMATCH:
                // Legacy getTileEntityAtSide returns null for both cases.
                // MISMATCH deliberately leaves the old cached object intact.
                return LegacyPowerNeighborLookup.loadedWithoutBlockEntity();
            case TILE:
                return LegacyPowerNeighborLookup.loadedWithBlockEntity(cached.tile());
            case MISS:
                break;
        }

        LevelChunk chunk = level.getChunkSource().getChunkNow(
            target.getX() >> 4,
            target.getZ() >> 4);
        if (chunk == null) {
            LegacyPowerNeighborLookup unloaded = LegacyPowerNeighborLookup.unloaded();
            cache.remember(side, unloaded);
            return unloaded;
        }

        BlockEntity blockEntity = chunk.getBlockEntity(target);
        LegacyPowerNeighborLookup result = blockEntity == null
            ? LegacyPowerNeighborLookup.loadedWithoutBlockEntity()
            : LegacyPowerNeighborLookup.loadedWithBlockEntity(blockEntity);
        cache.remember(side, result);
        return result;
    }

    public boolean crossesChunkBorder(LegacyPowerDirection side) {
        Direction direction = toMinecraftDirection(side);
        BlockPos target = origin.relative(direction);
        return (origin.getX() >> 4) != (target.getX() >> 4)
            || (origin.getZ() >> 4) != (target.getZ() >> 4);
    }

    /** Mirrors BaseTileEntity.clearNullMarkersFromTileEntityBuffer(). */
    public void clearEmptyMarkers() {
        cache.clearEmptyMarkers();
    }

    /** Mirrors BaseTileEntity.clearTileEntityBuffer(). */
    public void clearAll() {
        cache.clearAll();
    }

    public BlockPos origin() {
        return origin;
    }

    private static Direction toMinecraftDirection(LegacyPowerDirection side) {
        Objects.requireNonNull(side, "side");
        return switch (side) {
            case DOWN -> Direction.DOWN;
            case UP -> Direction.UP;
            case NORTH -> Direction.NORTH;
            case SOUTH -> Direction.SOUTH;
            case WEST -> Direction.WEST;
            case EAST -> Direction.EAST;
            case UNKNOWN -> throw new IllegalArgumentException(
                "UNKNOWN is not a physical neighbor direction");
        };
    }
}
